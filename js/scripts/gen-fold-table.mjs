// Embed conformance/name_fold.json (SDK spec 4.4.1) as src/fold-table.ts.
//   node scripts/gen-fold-table.mjs          write the file
//   node scripts/gen-fold-table.mjs --check  exit 1 if the committed file is not current
import { readFileSync, writeFileSync } from "node:fs";

const src = new URL("../../conformance/name_fold.json", import.meta.url);
const dst = new URL("../src/fold-table.ts", import.meta.url);
const doc = JSON.parse(readFileSync(src, "utf8"));
const entries = Object.entries(doc.map).map(([k, v]) => [parseInt(k, 16), v]).sort((a, b) => a[0] - b[0]);
const body = entries.map(([cp, v]) => `    [0x${cp.toString(16).toUpperCase().padStart(4, "0")}, ${JSON.stringify(v)}],`).join("\n");
const text = `// Generated by scripts/gen-fold-table.mjs from conformance/name_fold.json (Unicode ${doc.unicode_version}). Do not edit.
export const FOLD_UNICODE_VERSION = ${JSON.stringify(doc.unicode_version)};
export const FOLD_TABLE: ReadonlyMap<number, string> = new Map<number, string>([
${body}
]);
`;
if (process.argv.includes("--check")) {
    let cur = "";
    try { cur = readFileSync(dst, "utf8"); } catch { /* missing */ }
    if (cur !== text) { console.error("src/fold-table.ts is not current: run npm run gen"); process.exit(1); }
    console.log(`OK: src/fold-table.ts is current (${entries.length} code points)`);
} else {
    writeFileSync(dst, text);
    console.log(`wrote src/fold-table.ts (${entries.length} code points)`);
}
