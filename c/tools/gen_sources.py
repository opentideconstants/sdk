# /// script
# requires-python = ">=3.10"
# ///
"""Generate the C library's derived sources (run from the repository root):

    uv run c/tools/gen_sources.py           write the files
    uv run c/tools/gen_sources.py --check   exit 1 if a committed file differs
    uv run c/tools/gen_sources.py --symbols c/build/libopentideconstants.a
                                            exit 1 if the built library defines a global
                                            symbol without the otc_ prefix (nm)

- c/src/otc_cjson_rename.h: renames every public cJSON symbol to otc__cJSON_*,
  so an application can link its own cJSON next to this library.
- c/src/otc_sha256_rename.h: the same for the vendored SHA-256.
- c/src/otc_fold_table.c: conformance/name_fold.json as a sorted C table
  (SDK spec 4.4.1).

Every file is read and written as UTF-8 bytes with LF line ends, and --check
compares bytes, so a CRLF checkout of a generated file is out of date on every
OS (R3-314).
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
C = ROOT / "c"


def read(path):
    return path.read_bytes().decode("utf-8")


def rename_header(guard, names, source):
    lines = [f"/* Generated by c/tools/gen_sources.py from {source}; do not edit. */",
             f"#ifndef {guard}", f"#define {guard}"]
    lines += [f"#define {n} otc__{n}" for n in names]
    lines += [f"#endif /* {guard} */", ""]
    return "\n".join(lines)


# An external function definition at the start of a line: a return type (any
# words and stars), the name, "(" (C80: not only "void" and "uint8_t *"). The
# return type may end its own line ("int\nname("), so the gap before the name
# may hold a newline.
EXTERNAL_DEF = re.compile(r"^(?!static\b)(?!typedef\b)[A-Za-z_][\w \t\*\(\)]*?[\s\*\)]([A-Za-z_]\w*)\s*\(", re.M)
# A line that only starts a declaration with static ("static" or "static int" on
# its own line): a match on the next line belongs to that static declaration (R3-321).
STATIC_HEAD = re.compile(r"^\s*static\b[^;{}()]*$")


def external_functions(path, prefix=""):
    text = read(path)
    names = set()
    for m in EXTERNAL_DEF.finditer(text):
        before = text[:m.start()].rstrip("\n").rsplit("\n", 1)[-1] if m.start() else ""
        if STATIC_HEAD.match(before):
            continue
        if m.group(1).startswith(prefix):
            names.add(m.group(1))
    return names - {"if", "for", "while", "switch", "return", "sizeof"}


def checked(names, what, minimum):
    """A list that is too short means a parse that missed the source: fail, never write it (C80)."""
    if len(names) < minimum:
        sys.exit(f"gen_sources: found {len(names)} {what} symbols (at least {minimum} expected); "
                 "the vendored source changed shape - fix the parse before generating")
    return sorted(names)


def cjson_names():
    text = read(C / "vendor/cjson/cJSON.h")
    declared = set(re.findall(r"CJSON_PUBLIC\([^)]*\)\s*([A-Za-z_][A-Za-z0-9_]*)\s*\(", text))
    # cJSON.c also has external functions that cJSON.h does not declare (cJSON_Duplicate_rec)
    defined = external_functions(C / "vendor/cjson/cJSON.c", "cJSON_")
    if not declared:
        sys.exit("gen_sources: no CJSON_PUBLIC declarations in cJSON.h; the vendored header changed shape")
    return checked({n for n in declared | defined if n.startswith("cJSON_")}, "cJSON", 60)


def sha_names():
    text = read(C / "vendor/sha256/sha-256.h")
    declared = {n for n in re.findall(r"^\s*[A-Za-z_][\w \t\*]*?[\s\*]([a-z_0-9]+)\s*\(", text, re.M)}
    defined = external_functions(C / "vendor/sha256/sha-256.c")
    if declared != defined:
        sys.exit(f"gen_sources: sha-256.h declares {sorted(declared)} but sha-256.c defines {sorted(defined)}")
    return checked(declared, "SHA-256", 4)


def c_escape(s):
    out = []
    for b in s.encode("utf-8"):
        if 0x20 <= b < 0x7F and b not in (0x22, 0x5C, 0x3F):
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")
    return "".join(out)


# conformance/name_fold.json has 882 code points; far fewer means the wrong file (R3-321).
MIN_FOLD_ROWS = 100


def fold_table():
    doc = json.loads(read(ROOT / "conformance/name_fold.json"))
    rows = sorted((int(k, 16), v) for k, v in doc["map"].items())
    if len(rows) < MIN_FOLD_ROWS:
        sys.exit(f"gen_sources: conformance/name_fold.json maps {len(rows)} code points "
                 f"(at least {MIN_FOLD_ROWS} expected)")
    dup = sorted({cp for (cp, _), (nxt, _) in zip(rows, rows[1:]) if cp == nxt})
    if dup:   # "41" and "0041": two rows for one code point break the C binary search
        sys.exit(f"gen_sources: conformance/name_fold.json maps a code point more than once: "
                 f"{', '.join(f'U+{cp:04X}' for cp in dup)}")
    lines = ["/* Generated by c/tools/gen_sources.py from conformance/name_fold.json",
             f" * (Unicode {doc['unicode_version']}); do not edit. SDK spec 4.4.1. */",
             '#include "otc_internal.h"', "",
             "const otc_fold_entry otc__fold_table[] = {"]
    lines += [f'    {{0x{cp:04X}u, "{c_escape(v)}"}},' for cp, v in rows]
    lines += ["};", f"const size_t otc__fold_table_size = {len(rows)};", ""]
    return "\n".join(lines)


# The library defines about 215 public otc_ functions and 154 renamed otc__
# vendor symbols. Far fewer means nm read the wrong file or printed nothing
# usable, and an empty list must not pass (R2-240).
MIN_OTC_SYMBOLS = 100
# A sanitizer build adds the compiler's own globals (___asan_globals_registered,
# __odr_asan_gen_<name>); they are instrumentation, not a name of this library.
SANITIZER_SYMBOL = re.compile(r"_{2,3}(odr_asan|asan|ubsan|tsan|msan|sancov|sanitizer)_")


def check_symbols(lib):
    """The nm backstop (C80): every global symbol a built library defines starts with otc_."""
    import subprocess
    out = subprocess.run(["nm", "-g", lib], capture_output=True, text=True)
    if out.returncode != 0:
        print(f"nm {lib} failed: {out.stderr.strip()}")
        return 1
    bad = []
    good = 0
    for line in out.stdout.splitlines():
        parts = line.split()
        if len(parts) < 3 or parts[-2] in ("U", "w", "v"):
            continue   # an undefined (or weak undefined) reference, or an archive member line
        name = parts[-1]
        if sys.platform == "darwin" and name.startswith("_"):
            name = name[1:]
        if name.startswith("otc_"):
            good += 1
        elif not SANITIZER_SYMBOL.match(name):
            bad.append(name)
    for name in sorted(set(bad)):
        print(f"{lib}: global symbol without the otc_ prefix: {name}")
    if good < MIN_OTC_SYMBOLS:
        print(f"{lib}: nm shows {good} defined otc_ symbols (at least {MIN_OTC_SYMBOLS} expected); "
              "not the library, or nm printed nothing usable")
        return 1
    if not bad:
        print(f"{lib}: {good} global symbols, all with the otc_ prefix")
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--symbols", metavar="LIB", help="check that every global symbol LIB defines starts with otc_")
    a = ap.parse_args()
    if a.symbols:
        return check_symbols(a.symbols)
    files = {
        C / "src/otc_cjson_rename.h": rename_header("OTC_CJSON_RENAME_H", cjson_names(),
                                                   "c/vendor/cjson/cJSON.h and cJSON.c"),
        C / "src/otc_sha256_rename.h": rename_header("OTC_SHA256_RENAME_H", sha_names(),
                                                    "c/vendor/sha256/sha-256.h and sha-256.c"),
        C / "src/otc_fold_table.c": fold_table(),
    }
    bad = 0
    for path, text in files.items():
        data = text.encode("utf-8")
        if a.check:
            if not path.exists() or path.read_bytes() != data:
                print(f"out of date: {path.relative_to(ROOT)}")
                bad = 1
        else:
            path.write_bytes(data)
    return bad


if __name__ == "__main__":
    sys.exit(main())
